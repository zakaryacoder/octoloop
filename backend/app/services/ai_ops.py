AI_QUERY_DISCLAIMER = (
    "DISCLAIMER: Operational-only answer derived from aggregated system data. "
    "Not clinical advice; may be incomplete; verify against source records before acting."
)


def _dashboard_data(db: Session) -> dict:
    today = datetime.now(timezone.utc).date()
    total_patients = db.query(func.count(Patient.id)).scalar() or 0
    total_screenings = db.query(func.count(Screening.id)).scalar() or 0
    abnormal = db.query(func.count(Screening.id)).filter(Screening.result_classification == "ABNORMAL").scalar() or 0
    open_cases = db.query(FollowUpCase).filter(FollowUpCase.status != "CLOSED").all()
    overdue = [c for c in open_cases if is_case_overdue(c, today)]
    closed = db.query(func.count(FollowUpCase.id)).filter(FollowUpCase.status == "CLOSED").scalar() or 0
    total_cases = len(open_cases) + closed
    completion = round(100.0 * closed / total_cases, 1) if total_cases else 0.0
    pending_refs = db.query(func.count(Referral.id)).filter(Referral.status.in_(["DRAFT", "SENT"])).scalar() or 0
    return {
        "total_patients": total_patients, "total_screenings": total_screenings,
        "abnormal_results": abnormal, "open_cases": len(open_cases),
        "overdue_cases": len(overdue), "closed_cases": closed,
        "follow_up_completion_rate": completion, "pending_referrals": pending_refs,
        "top_overdue": [{"case_ref": c.case_ref, "days_overdue": (today - c.due_date).days}
                        for c in sorted(overdue, key=lambda c: (today - c.due_date).days, reverse=True)[:5]],
    }


def _population_data(db: Session) -> dict:
    total_screenings = db.query(func.count(Screening.id)).scalar() or 0
    abnormal = db.query(func.count(Screening.id)).filter(Screening.result_classification == "ABNORMAL").scalar() or 0
    abnormal_rate = round(100.0 * abnormal / total_screenings, 1) if total_screenings else 0.0
    closed = db.query(func.count(FollowUpCase.id)).filter(FollowUpCase.status == "CLOSED").scalar() or 0
    total_cases = db.query(func.count(FollowUpCase.id)).scalar() or 0
    completion = round(100.0 * closed / total_cases, 1) if total_cases else 0.0
    return {"screening_volume": total_screenings, "abnormal_rate": abnormal_rate,
            "follow_up_completion_rate": completion}


def _escalation_data(db: Session) -> dict:
    from app.models.escalation import EscalationLog
    today = datetime.now(timezone.utc).date()
    open_cases = db.query(FollowUpCase).filter(FollowUpCase.status != "CLOSED").all()
    overdue = [c for c in open_cases if is_case_overdue(c, today)]
    recent_logs = db.query(EscalationLog).order_by(EscalationLog.created_at.desc()).limit(5).all()
    return {"overdue_open_cases": len(overdue),
            "recent_escalations": [{"case_id": l.case_id, "level": l.level, "detail": l.detail[:80]} for l in recent_logs]}


def _llm_enhance(question: str, deterministic_answer: str, minimized_data: dict) -> str | None:
    """Optional LLM. PHI-minimized: only question + aggregated metrics + event-type labels.
    10s timeout; on ANY error return None (caller uses deterministic fallback). Never sends notes/PHI."""
    if settings.LLM_PROVIDER.lower() == "none" or not settings.LLM_API_KEY:
        return None
    import httpx
    payload = {
        "model": settings.LLM_MODEL,
        "messages": [
            {"role": "system", "content": "You are an operational health-admin assistant. "
             "Answer using only the provided aggregated metrics. Never give clinical advice. "
             "If unsure, say so. Do not invent patient data."},
            {"role": "user", "content": f"Question: {question}\nAggregated metrics: {minimized_data}\n"
             f"Deterministic draft answer: {deterministic_answer}\nRefine concisely (operational only)."},
        ],
        "max_tokens": 300, "temperature": 0.2,
    }
    headers = {"Authorization": f"Bearer {settings.LLM_API_KEY}", "Content-Type": "application/json"}
    url = "https://api.openai.com/v1/chat/completions" if settings.LLM_PROVIDER.lower() == "openai" \
        else "https://api.anthropic.com/v1/messages"
    try:
        r = httpx.post(url, json=payload, headers=headers, timeout=settings.LLM_TIMEOUT_SECONDS)
        if r.status_code == 200:
            data = r.json()
            if settings.LLM_PROVIDER.lower() == "openai":
                return data["choices"][0]["message"]["content"]
            return data["content"][0]["text"]
        return None
    except Exception:  # noqa: BLE001 — any failure -> deterministic fallback
        return None


def query_dashboard(db: Session, question: str) -> dict:
    """Deterministic keyword-routed operational answer. Optional LLM refinement (PHI-minimized).
    ALWAYS returns disclaimer. Never diagnoses/prescribes/closes/fabricates PHI."""
    q = (question or "").lower()
    if any(w in q for w in ["population", "coverage", "abnormal rate", "screening rate", "completion rate"]):
        routed_to = "population"
        data = _population_data(db)
        answer = (f"Population overview: {data['screening_volume']} screenings, "
                  f"abnormal rate {data['abnormal_rate']}%, follow-up completion {data['follow_up_completion_rate']}%. "
                  "All figures are aggregated and anonymized operational metrics.")
    elif any(w in q for w in ["escalat", "overdue", "delay", "bottleneck", "stuck"]):
        routed_to = "escalation"
        data = _escalation_data(db)
        answer = (f"{data['overdue_open_cases']} open case(s) are currently overdue. "
                  f"{len(data['recent_escalations'])} recent escalation(s) recorded. "
                  "Review the top-overdue list and contact responsible staff immediately.")
    elif any(w in q for w in ["dashboard", "summary", "overview", "kpi", "total", "how many"]):
        routed_to = "dashboard"
        data = _dashboard_data(db)
        answer = (f"Dashboard: {data['total_patients']} patients, {data['total_screenings']} screenings, "
                  f"{data['abnormal_results']} abnormal, {data['open_cases']} open cases "
                  f"({data['overdue_cases']} overdue), completion rate {data['follow_up_completion_rate']}%, "
                  f"{data['pending_referrals']} pending referrals.")
    else:
        routed_to = "unknown"
        data = _dashboard_data(db)
        answer = ("I can answer operational questions about dashboard KPIs, population health "
                  "(aggregated/anonymized), and overdue/escalation status. Try asking about "
                  "'overdue cases', 'population completion rate', or 'dashboard summary'.")

    # Optional LLM refinement with PHI-minimized payload (no notes, no PHI).
    enhanced = _llm_enhance(question, answer, data)
    final_answer = enhanced if enhanced else answer

    return {
        "answer": final_answer,
        "routed_to": routed_to,
        "data": data,
        "disclaimer": AI_QUERY_DISCLAIMER,
    }
